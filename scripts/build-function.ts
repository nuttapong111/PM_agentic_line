// Bundles the bot into ONE TypeScript-compatible file for a Railway Function (Bun runtime, no repo needed).
// npm packages stay as versioned imports (Bun installs them); local modules and assets are inlined.
import { build } from "esbuild";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const pkg = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"));
const version = (name: string) => String(pkg.dependencies[name] ?? "").replace(/^[\^~]/, "");

const html = fs.readFileSync(path.join(root, "public/dashboard.html"), "utf8");
const png = fs.readFileSync(path.join(root, "assets/richmenu.png")).toString("base64");

const result = await build({
  entryPoints: [path.join(root, "src/server.ts")],
  bundle: true,
  write: false,
  format: "esm",
  platform: "node",
  target: "esnext",
  legalComments: "none",
  plugins: [
    {
      name: "inline-assets-and-pin-packages",
      setup(b) {
        b.onResolve({ filter: /\/assets\.js$/ }, () => ({ path: "assets", namespace: "inline" }));
        b.onLoad({ filter: /.*/, namespace: "inline" }, () => ({
          loader: "js",
          contents:
            `export const dashboardHtml = () => ${JSON.stringify(html)};\n` +
            `export const richMenuImage = () => Buffer.from(${JSON.stringify(png)}, "base64");\n`,
        }));
        // Bare package imports → "name@version" so Bun installs the same versions we tested with.
        b.onResolve({ filter: /^[^./]/ }, (args) => {
          if (args.path.startsWith("node:")) return { path: args.path, external: true };
          const m = args.path.match(/^(@[^/]+\/[^/]+|[^/]+)(\/.*)?$/)!;
          const v = version(m[1]);
          if (!v) return { path: args.path, external: true };
          return { path: m[2] ? args.path : `${m[1]}@${v}`, external: true };
        });
      },
    },
  ],
});

const out = path.join(root, "dist/function.ts");
fs.mkdirSync(path.dirname(out), { recursive: true });
const header = "// @ts-nocheck\n// GENERATED by scripts/build-function.ts — edit src/ and rebuild.\n";
fs.writeFileSync(out, header + result.outputFiles[0].text);
console.log(`wrote ${out} (${(fs.statSync(out).size / 1024).toFixed(0)} KB)`);
